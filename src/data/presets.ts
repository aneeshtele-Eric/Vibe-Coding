// Helper to match origin string to closest hub city
export function detectOriginHub(origin: string): string {
  const norm = origin.toLowerCase().trim();
  if (norm.includes('bengaluru') || norm.includes('bangalore') || norm.includes('blr')) return 'Bengaluru';
  if (norm.includes('mumbai') || norm.includes('bombay') || norm.includes('pune')) return 'Mumbai';
  if (norm.includes('delhi') || norm.includes('gurgaon') || norm.includes('noida') || norm.includes('ncr')) return 'Delhi';
  if (norm.includes('san francisco') || norm.includes('sf') || norm.includes('bay area') || norm.includes('oakland') || norm.includes('san jose')) return 'San Francisco';
  if (norm.includes('tokyo') || norm.includes('shinjuku') || norm.includes('shibuya') || norm.includes('yokohama')) return 'Tokyo';
  if (norm.includes('london') || norm.includes('marylebone') || norm.includes('paddington')) return 'London';
  if (norm.includes('paris') || norm.includes('versailles')) return 'Paris';
  return '';
}

// Function to filter corridors based on origin and day count
export function getFilteredCorridors(
  origin: string,
  selectedDays: number | 'all'
): PresetDestination[] {
  const hub = detectOriginHub(origin);

  let pool = ALL_CORRIDORS;

  // If a known hub is detected, strictly prioritize or isolate corridors from that hub
  if (hub) {
    const hubMatches = ALL_CORRIDORS.filter(
      (c) => c.originCity.toLowerCase() === hub.toLowerCase()
    );
    if (hubMatches.length > 0) {
      pool = hubMatches;
    }
  } else {
    // If user typed a custom city (e.g. Hyderabad, Chennai, New York, etc.),
    // check if any corridor origin includes the typed query
    const query = origin.toLowerCase().trim();
    if (query) {
      const textMatches = ALL_CORRIDORS.filter((c) =>
        c.origin.toLowerCase().includes(query) || c.originCity.toLowerCase().includes(query)
      );
      if (textMatches.length > 0) {
        pool = textMatches;
      }
    }
  }

  // Now filter by selected days if specified
  if (selectedDays !== 'all') {
    const daysNum = typeof selectedDays === 'number' ? selectedDays : parseInt(selectedDays, 10);
    if (!isNaN(daysNum)) {
      const daysMatches = pool.filter(
        (c) => daysNum >= c.minDays && daysNum <= c.maxDays
      );
      if (daysMatches.length > 0) {
        // Sort with idealDays === daysNum first
        return daysMatches.sort((a, b) => {
          const aExact = a.idealDays === daysNum ? 1 : 0;
          const bExact = b.idealDays === daysNum ? 1 : 0;
          return bExact - aExact;
        });
      }
    }
  }

  return pool;
}

